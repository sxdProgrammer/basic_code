const ThemeContext = createContext();

export function ThemeProvider({ children }) {
  const [themeName, setThemeName] = useState(() => {
    return localStorage.getItem('it-request-theme') || 'purple';
  });

  useEffect(() => {
    const theme = THEMES[themeName];
    if (!theme) return;
    const root = document.documentElement;

    Object.entries(theme).forEach(([key, value]) => {
      if (key.startsWith('--')) {
        root.style.setProperty(key, value);
      }
    });

    root.setAttribute('data-theme', theme.mode || 'dark');
    localStorage.setItem('it-request-theme', themeName);
  }, [themeName]);

  return (
    <ThemeContext.Provider value={{ themeName, setThemeName, themes: THEMES, currentTheme: THEMES[themeName] }}>
      {children}
    </ThemeContext.Provider>
  );
}

export function useTheme() {
  return useContext(ThemeContext);
}

export { THEMES };
